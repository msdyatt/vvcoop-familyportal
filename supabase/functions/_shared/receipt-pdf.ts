/**
 * A one-page PDF receipt, written by hand: the standard Helvetica fonts need no
 * embedding, so there is no library and no font file to ship. Text outside
 * Latin-1 is replaced with "?" rather than risk a broken file.
 */

export type ReceiptData = {
  kind: "payment" | "refund";
  orgName: string;
  orgEin: string | null;
  orgAddress: string | null;
  footerNote: string | null;
  receiptNumber: string;
  date: string;               // already formatted, e.g. "September 2, 2026"
  household: string;
  description: string;
  amount: string;             // already formatted, e.g. "$600.00"
  method: string;
  reference: string | null;
  testMode: boolean;
};

const PAGE_W = 612;
const PAGE_H = 792;

function esc(text: string): string {
  return [...text].map((ch) => {
    const code = ch.codePointAt(0)!;
    if (ch === "\\" || ch === "(" || ch === ")") return `\\${ch}`;
    if (code === 0x2013 || code === 0x2014) return "-";
    if (code === 0x2018 || code === 0x2019) return "'";
    if (code === 0x201c || code === 0x201d) return '"';
    if (code === 0x2022) return "\\225";
    if (code < 32 || code > 255) return "?";
    if (code > 126) return `\\${code.toString(8).padStart(3, "0")}`;
    return ch;
  }).join("");
}

/** Greedy word wrap at roughly `max` characters. */
function wrap(text: string, max: number): string[] {
  const lines: string[] = [];
  for (const paragraph of text.split("\n")) {
    let line = "";
    for (const word of paragraph.split(/\s+/).filter(Boolean)) {
      if ((line + " " + word).trim().length > max && line) { lines.push(line); line = word; } else { line = (line + " " + word).trim(); }
    }
    lines.push(line);
  }
  return lines;
}

export function buildReceiptPdf(r: ReceiptData): Uint8Array {
  const ops: string[] = [];
  const text = (x: number, y: number, size: number, value: string, bold = false) =>
    ops.push(`BT /${bold ? "F2" : "F1"} ${size} Tf ${x} ${y} Td (${esc(value)}) Tj ET`);
  const rule = (y: number) => ops.push(`0.75 w 54 ${y} m ${PAGE_W - 54} ${y} l S`);

  let y = PAGE_H - 72;
  text(54, y, 20, r.orgName, true); y -= 16;
  if (r.orgEin) { text(54, y, 10, `EIN ${r.orgEin}`); y -= 13; }
  for (const line of wrap(r.orgAddress ?? "", 80)) { if (line) { text(54, y, 10, line); y -= 13; } }
  y -= 8; rule(y); y -= 34;

  text(54, y, 16, r.kind === "refund" ? "Refund confirmation" : "Payment receipt", true);
  text(PAGE_W - 54 - 150, y, 11, `No. ${r.receiptNumber}`, true); y -= 30;

  const row = (label: string, value: string) => {
    text(54, y, 10, label.toUpperCase());
    const lines = wrap(value, 62);
    lines.forEach((line, i) => text(190, y - i * 14, 12, line));
    y -= Math.max(lines.length, 1) * 14 + 12;
  };
  row("Date", r.date);
  row("Household", r.household);
  row("For", r.description);
  row("Paid by", r.method);
  if (r.reference) row("Reference", r.reference);
  y -= 4; rule(y); y -= 30;
  text(54, y, 12, r.kind === "refund" ? "Amount refunded" : "Amount paid", true);
  text(PAGE_W - 54 - 130, y, 18, r.amount, true); y -= 24; rule(y); y -= 28;

  if (r.footerNote) for (const line of wrap(r.footerNote, 92)) { text(54, y, 10, line); y -= 13; }
  if (r.testMode) {
    ops.push("BT /F2 16 Tf 54 90 Td (TEST MODE - no real money moved. This is not a valid receipt.) Tj ET");
  }
  text(54, 54, 9, "Generated by Veritas Village Family Portal.");

  const content = ops.join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_W} ${PAGE_H}] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>`,
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
  ];

  let out = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((body, index) => { offsets.push(out.length); out += `${index + 1} 0 obj\n${body}\nendobj\n`; });
  const xref = out.length;
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) out += `${String(offset).padStart(10, "0")} 00000 n \n`;
  out += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;

  // Every character is single-byte (see esc), so length equals byte count.
  return Uint8Array.from(out, (ch) => ch.charCodeAt(0));
}
